use std::collections::BTreeMap;
use std::io::Write;

/// `#define __NR_<name> <number>` lines of one of the `*_syscall.h.in`
/// tables, in the order the file lists them.
fn read_table(path: &str) -> Vec<(String, u32)> {
    let data = std::fs::read_to_string(path).unwrap();
    let mut rows = Vec::new();
    for line in data.lines() {
        if !line.starts_with("#define") {
            continue;
        }
        let mut iter = line.split_whitespace();
        let _ = iter.next().unwrap();
        let name = iter.next().unwrap();
        let id = iter.next().unwrap();
        rows.push((name[5..].to_string(), id.parse().unwrap()));
    }
    rows
}

fn main() {
    let arch = std::env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let syscall_in = match arch.as_str() {
        "riscv64" => "src/riscv64_syscall.h.in",
        "aarch64" => "src/aarch64_syscall.h.in",
        _ => "src/syscall.h.in",
    };
    println!("cargo:rerun-if-changed={}", syscall_in);

    let native = read_table(syscall_in);

    let mut fout = std::fs::File::create(std::env::var("OUT_DIR").unwrap() + "/consts.rs").unwrap();
    writeln!(fout, "// Generated by build.rs. DO NOT EDIT.").unwrap();
    writeln!(fout, "use numeric_enum_macro::numeric_enum;\n").unwrap();
    writeln!(fout, "numeric_enum! {{").unwrap();
    writeln!(fout, "#[repr(u32)]").unwrap();
    writeln!(fout, "#[derive(Debug, Eq, PartialEq)]").unwrap();
    writeln!(fout, "#[allow(non_camel_case_types)]").unwrap();
    writeln!(fout, "pub enum SyscallType {{").unwrap();
    for (name, id) in &native {
        writeln!(fout, "    {} = {},", name.to_uppercase(), id).unwrap();
    }
    writeln!(fout, "}}").unwrap();
    writeln!(fout, "}}").unwrap();

    // The 32-bit (i386) table, for the compatibility mode an x86_64 kernel
    // runs an `ELFCLASS32` program in. Nothing else has a second table.
    if arch.is_empty() || arch == "x86_64" {
        compat32(&native);
    }
}

/// Emit the i386 -> native number mapping, and the i386 names.
///
/// Three inputs decide one row. A number comes from `i386_syscall.h.in`, the
/// native number it means comes from matching the **name** against the native
/// table -- and whether the row is emitted at all comes from
/// `i386_abi_same.in`, the allowlist of calls whose ABI is byte-for-byte the
/// native one.
///
/// Default-deny, because matching by name alone is not sound: `gettimeofday`
/// has that name in both tables and passes a `struct timeval` of two longs,
/// which is 8 bytes for the 32-bit caller and 16 for the native handler. Every
/// such call has to be converted, and until it is, answering `ENOSYS` is the
/// only honest thing to do. So the allowlist is the list that is maintained,
/// and a name missing from it costs an `ENOSYS` rather than a silent misread.
///
/// A name in the allowlist that is in neither table is a mistake worth
/// stopping the build for: it is a line that looks like it does something and
/// does nothing.
///
/// There are **two** allowlist files, read as one. `i386_abi_same.in` is the
/// calls that need no conversion at all. `i386_abi_narrow.in` is the calls
/// whose registers are already native but whose *structures* the handler
/// converts, because it asks the calling process how wide a word is
/// (`linux_syscall::narrow`, Linux's `in_compat_syscall()`): once that is
/// true of every structure a call passes, translating the number is again all
/// there is to do. Two files rather than one because the claim they make is
/// different, and a reader has to be able to tell which one is being made.
fn compat32(native: &[(String, u32)]) {
    const I386_IN: &str = "src/i386_syscall.h.in";
    const SAME_IN: &str = "src/i386_abi_same.in";
    const NARROW_IN: &str = "src/i386_abi_narrow.in";
    println!("cargo:rerun-if-changed={}", I386_IN);
    println!("cargo:rerun-if-changed={}", SAME_IN);
    println!("cargo:rerun-if-changed={}", NARROW_IN);

    let by_name: BTreeMap<&str, u32> = native.iter().map(|(n, id)| (n.as_str(), *id)).collect();
    let i386 = read_table(I386_IN);
    let i386_by_name: BTreeMap<&str, u32> = i386.iter().map(|(n, id)| (n.as_str(), *id)).collect();

    // Two files, read as one list and checked against each other for
    // duplicates. Each line is carried with the file it came from, so that a
    // name that is in neither table is reported against the file somebody has
    // to go and edit.
    let lists = [
        (SAME_IN, std::fs::read_to_string(SAME_IN).unwrap()),
        (NARROW_IN, std::fs::read_to_string(NARROW_IN).unwrap()),
    ];
    let mut abi_same = BTreeMap::new();
    for (from, line) in lists
        .iter()
        .flat_map(|(from, text)| text.lines().map(move |line| (*from, line)))
    {
        let line = line.trim();
        if line.is_empty() || line.starts_with("//") {
            continue;
        }
        // A bare name means the two tables call the call the same thing.
        // `i386_name = native_name` is for the ones i386 renamed, which are
        // all the same story: the original was 16-bit, so i386 grew a `*32`
        // number for the real thing, while x86_64 -- which never had a
        // 16-bit anything -- just calls it by its name. The ABI of the pair
        // is still identical, which is the only question those files answer.
        let (name32, name64) = match line.split_once('=') {
            Some((left, right)) => (left.trim(), right.trim()),
            None => (line, line),
        };
        let Some(&id32) = i386_by_name.get(name32) else {
            panic!("{}: {:?} is not a system call in {}", from, name32, I386_IN);
        };
        let Some(&id64) = by_name.get(name64) else {
            panic!(
                "{}: {:?} is not a system call this kernel implements",
                from, name64
            );
        };
        if abi_same.insert(name32.to_string(), (id32, id64)).is_some() {
            panic!("{} / {}: {:?} is listed twice", SAME_IN, NARROW_IN, name32);
        }
    }

    let mut out =
        std::fs::File::create(std::env::var("OUT_DIR").unwrap() + "/compat32.rs").unwrap();
    writeln!(
        out,
        "// Generated by build.rs from {}. DO NOT EDIT.",
        I386_IN
    )
    .unwrap();

    writeln!(
        out,
        "/// Every i386 system-call number and the name it goes by, sorted by\n\
         /// number: the whole of `syscall_32.tbl`, whether this kernel implements\n\
         /// it or not. Used to report an unimplemented call by name.\n\
         pub const I386_NAMES: &[(u32, &str)] = &["
    )
    .unwrap();
    let mut rows: Vec<_> = i386.iter().map(|(n, id)| (*id, n.as_str())).collect();
    rows.sort_unstable();
    for (id, name) in &rows {
        writeln!(out, "    ({}, {:?}),", id, name).unwrap();
    }
    writeln!(out, "];").unwrap();

    let mut mapped: Vec<(u32, u32)> = abi_same.values().copied().collect();
    mapped.sort_unstable();
    writeln!(
        out,
        "/// i386 number -> native number, for the calls `i386_abi_same.in`\n\
         /// says need no conversion and the ones `i386_abi_narrow.in` says\n\
         /// the handler converts itself, sorted by the i386 number. See\n\
         /// `build.rs::compat32`.\n\
         pub const I386_TO_NATIVE: &[(u32, u32)] = &["
    )
    .unwrap();
    for (id32, id64) in &mapped {
        writeln!(out, "    ({}, {}),", id32, id64).unwrap();
    }
    writeln!(out, "];").unwrap();
}
