#!/bin/sh
# Regenerates kernels_ptx.h, the PTX cuda-probe carries, from kernels.cu.
# Needs clang with the NVPTX target; checks the result with NVIDIA's ptxas
# when one is on PATH (or named by PTXAS).
set -eu
cd "$(dirname "$0")"
clang -x cuda --cuda-device-only --cuda-gpu-arch=sm_75 -nocudainc -nocudalib \
    -Xclang -target-feature -Xclang +ptx65 -O2 -S -o kernels.ptx kernels.cu
PTXAS=${PTXAS:-$(command -v ptxas || true)}
if [ -n "$PTXAS" ]; then
    "$PTXAS" -arch=sm_75 -o /dev/null kernels.ptx
else
    echo "warning: no ptxas; kernels_ptx.h is not checked" >&2
fi
{
    echo "// Generated by gen-kernels.sh from kernels.cu: do not edit by hand."
    echo "static const char kernels_ptx[] ="
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/    "/' -e 's/$/\\n"/' kernels.ptx
    echo "    ;"
} > kernels_ptx.h
rm -f kernels.ptx
